<#
.SYNOPSIS
    Writes THIRD_PARTY_LICENSES.txt: the license texts of every crate linked into the Windows
    x64 release binary, read from the crate packages Cargo already downloaded.

.DESCRIPTION
    The binary is published (GitHub releases, install.ps1), and MIT, BSD, ISC, Zlib, Apache-2.0,
    MPL-2.0 and Unicode-3.0 all ask for their notice or text to travel with it. The crate set is
    the normal (non-dev, non-build) dependency graph of the wingetrs package for
    x86_64-pc-windows-msvc, from `cargo metadata --locked --offline`. For each crate every
    top-level LICENSE*/LICENCE*/COPYING*/NOTICE*/COPYRIGHT*/UNLICENSE* file is copied verbatim.
    A crate without any such file fails the run (exit 1) unless it is listed in $Fallback with
    the reason, so a new dependency never ships without its notice.

    -Check compares the result with the committed file and exits 1 when it is stale (the gate
    runs this; regenerate with `pwsh -File scripts/third_party.ps1`).
#>
[CmdletBinding()]
param([switch]$Check)

Set-StrictMode -Version 2.0
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$out = Join-Path $root 'THIRD_PARTY_LICENSES.txt'
$target = 'x86_64-pc-windows-msvc'

# Crates whose package carries no license file (checked 2026-10-21): all declare MIT (alone or
# as "MIT OR Apache-2.0", where MIT is the one taken), so the standard MIT text stands in, with
# the holders from Cargo.toml `authors` or, when that is empty, the project's authors.
$Fallback = @{
    'base64-simd' = 'the simd project authors (https://github.com/Nugine/simd)'
    'vsimd' = 'the simd project authors (https://github.com/Nugine/simd)'
    'quantette' = 'the quantette authors (https://github.com/IanManske/quantette)'
    'icy_sixel' = 'Mike Krüger'
    'ratatui-termina' = 'Florian Dehau and The Ratatui Developers'
    'vtparse' = 'Wez Furlong'
    'wezterm-input-types' = 'Wez Furlong'
}
$MitText = @'
Permission is hereby granted, free of charge, to any person obtaining a copy of this software
and associated documentation files (the "Software"), to deal in the Software without
restriction, including without limitation the rights to use, copy, modify, merge, publish,
distribute, sublicense, and/or sell copies of the Software, and to permit persons to whom the
Software is furnished to do so, subject to the following conditions:

The above copyright notice and this permission notice shall be included in all copies or
substantial portions of the Software.

THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR IMPLIED, INCLUDING
BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY, FITNESS FOR A PARTICULAR PURPOSE AND
NONINFRINGEMENT. IN NO EVENT SHALL THE AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM,
DAMAGES OR OTHER LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM,
OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE SOFTWARE.
'@

$json = & cargo metadata --format-version 1 --locked --offline --filter-platform $target --manifest-path (Join-Path $root 'Cargo.toml')
if ($LASTEXITCODE -ne 0) { throw "cargo metadata falhou ($LASTEXITCODE)" }
$meta = $json | ConvertFrom-Json

$pkgs = @{}
foreach ($p in $meta.packages) { $pkgs[$p.id] = $p }
$nodes = @{}
foreach ($n in $meta.resolve.nodes) { $nodes[$n.id] = $n }
$rootId = ($meta.packages | Where-Object { $_.name -eq 'wingetrs' -and $meta.workspace_members -contains $_.id }).id

# Walk normal edges only: dev-dependencies and build scripts never reach the shipped binary.
$seen = New-Object 'System.Collections.Generic.HashSet[string]'
$queue = New-Object 'System.Collections.Generic.Queue[string]'
$queue.Enqueue($rootId)
while ($queue.Count -gt 0) {
    $id = $queue.Dequeue()
    foreach ($d in $nodes[$id].deps) {
        $normal = @($d.dep_kinds | Where-Object { $null -eq $_.kind -or $_.kind -eq 'normal' }).Count -gt 0
        if ($normal -and $seen.Add($d.pkg)) { $queue.Enqueue($d.pkg) }
    }
}

$pattern = '^(licen[cs]e|copying|notice|copyright|unlicense)([-._].*)?$'
$sb = New-Object System.Text.StringBuilder
[void]$sb.Append("Third-party software in wingetrs`n")
[void]$sb.Append("Generated by scripts/third_party.ps1 from Cargo.lock ($target, normal dependencies).`n")
[void]$sb.Append("wingetrs itself is MIT licensed (see LICENSE); NOTICE lists the attributions in short.`n")
$missing = @()
$list = @($seen | ForEach-Object { $pkgs[$_] } | Sort-Object name, version)
[void]$sb.Append("Components: $($list.Count)`n")
foreach ($p in $list) {
    $dir = Split-Path -Parent $p.manifest_path
    $lic = if ($p.license) { $p.license } elseif ($p.license_file) { "see $($p.license_file)" } else { 'unspecified' }
    $repo = if ($p.repository) { $p.repository } else { '-' }
    [void]$sb.Append("`n" + ('=' * 80) + "`n$($p.name) $($p.version)`nLicense: $lic`nRepository: $repo`n" + ('=' * 80) + "`n")
    $files = @(Get-ChildItem -LiteralPath $dir -File | Where-Object { $_.Name -match $pattern } | Sort-Object Name)
    if ($p.license_file) {
        $lf = Join-Path $dir $p.license_file
        if ((Test-Path -LiteralPath $lf) -and -not ($files | Where-Object { $_.FullName -eq (Resolve-Path -LiteralPath $lf).Path })) { $files += Get-Item -LiteralPath $lf }
    }
    if ($files.Count -eq 0) {
        if ($Fallback.ContainsKey($p.name) -and $lic -match '\bMIT\b') {
            [void]$sb.Append("`n--- MIT (the crate package ships no license file; standard text) ---`nCopyright (c) $($Fallback[$p.name])`n`n$($MitText.Replace("`r`n", "`n").TrimEnd())`n")
        }
        else { $missing += "$($p.name) $($p.version) ($lic)" }
        continue
    }
    foreach ($f in $files) {
        $text = [IO.File]::ReadAllText($f.FullName).Replace("`r`n", "`n").TrimEnd()
        [void]$sb.Append("`n--- $($f.Name) ---`n$text`n")
    }
}

if ($missing.Count -gt 0) {
    Write-Host 'Crates sem arquivo de licença no pacote (acrescente a $Fallback com o texto e o motivo):' -ForegroundColor Red
    $missing | ForEach-Object { Write-Host "  $_" }
    exit 1
}

$text = $sb.ToString()
if ($Check) {
    $old = if (Test-Path -LiteralPath $out) { [IO.File]::ReadAllText($out).Replace("`r`n", "`n") } else { '' }
    if ($old -ne $text) {
        Write-Host 'THIRD_PARTY_LICENSES.txt desatualizado: rode pwsh -File scripts/third_party.ps1' -ForegroundColor Red
        exit 1
    }
    Write-Host "THIRD_PARTY_LICENSES.txt em dia ($($list.Count) componentes)"
    exit 0
}
[IO.File]::WriteAllText($out, $text, (New-Object System.Text.UTF8Encoding $false))
Write-Host "THIRD_PARTY_LICENSES.txt: $($list.Count) componentes"
