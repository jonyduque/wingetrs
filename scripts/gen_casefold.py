"""Generate src/installed/casefold_table.rs from Unicode CaseFolding.txt (status C + F).

Usage: python -I scripts/gen_casefold.py [path/to/CaseFolding.txt]
Without an argument the file is downloaded from the URL below.
Matches ICU U_FOLD_CASE_DEFAULT (what winget's FoldCase uses).
"""
import sys
import urllib.request

URL = "https://www.unicode.org/Public/UCD/latest/ucd/CaseFolding.txt"
OUT = "src/installed/casefold_table.rs"
BS = chr(92)


def main():
    if len(sys.argv) > 1:
        with open(sys.argv[1], encoding="utf-8") as f:
            text = f.read()
    else:
        text = urllib.request.urlopen(URL).read().decode("utf-8")
    version = text.splitlines()[0].lstrip("# ").strip()
    rows = []
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        code, status, mapping, _ = [p.strip() for p in line.split(";")]
        if status not in ("C", "F"):
            continue
        target = "".join(chr(int(h, 16)) for h in mapping.split())
        rows.append((int(code, 16), target))
    rows.sort()
    out = [
        f"// Generated by scripts/gen_casefold.py from {version}",
        f"// Source: {URL}",
        "// Statuses C + F (ICU U_FOLD_CASE_DEFAULT). Do not edit by hand.",
        "",
        "pub(super) static CASE_FOLDING: &[(char, &str)] = &[",
    ]
    for cp, target in rows:
        esc = "".join("{}u{{{:X}}}".format(BS, ord(c)) for c in target)
        out.append("    ('{}u{{{:X}}}', \"{}\"),".format(BS, cp, esc))
    out.append("];")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")


main()
